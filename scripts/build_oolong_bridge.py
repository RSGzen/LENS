"""Build the OOLONG bridge: documents, the instrument file, and both campaigns.

Run once, after the raw rows are fetched:

    python scripts/build_oolong_bridge.py

The raw file is the 50 `trec_coarse` rows at 131072 from the release's validation
split; see `Evaluation.md` 6.1 for how they were obtained and why the split is
validation rather than test.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from lens import config
from lens.experiments.oolong import (
    build_instance,
    check_context,
    document_name,
    split_context,
    write_document,
)

RAW = Path(r"D:\lens-data\campaigns\w3\raw\trec_coarse-131072.jsonl")
INSTRUMENTS = Path(r"D:\lens\experiments\instruments")
CAMPAIGNS = Path(r"D:\lens\experiments\campaigns")
SUBSET_EVERY = 5
SEED = 20261114
ARMS = [
    {
        "name": "a0-doc",
        "env": {
            "LENS_RECORDED": "1",
            "LENS_EVIDENCE": "document",
            "LENS_MODE": "naive",
            "LENS_PROMPT_VARIANT": "naive",
            "LENS_GATE": "0",
            "LENS_SUB_CALLS": "0",
        },
        "note": "A0-doc: the whole document in one prompt, one call. No loop, no tools.",
    },
    {
        "name": "a2-doc",
        "env": {
            "LENS_RECORDED": "1",
            "LENS_EVIDENCE": "document",
            "LENS_MODE": "rlm",
            "LENS_PROMPT_VARIANT": "document",
            "LENS_SUB_CALLS": "0",
            "LENS_KG_ENABLED": "0",
            "LENS_KG_PROMPT": "0",
            "LENS_GATE": "1",
        },
        "note": (
            "A2-doc: REPL over the same file. Sub-calls are 0 because the document prompt "
            "advertises no sub-task and sub_extract hydrates ids from the database, so the "
            "route would be a capability the run cannot use. The final gate and the claim "
            "pass are skipped in document mode and the skip is logged."
        ),
    },
]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Build the OOLONG bridge instrument")
    parser.add_argument("--raw", default=str(RAW))
    parser.add_argument("--instruments", default=str(INSTRUMENTS))
    parser.add_argument("--campaigns", default=str(CAMPAIGNS))
    args = parser.parse_args(argv)

    rows = [
        json.loads(line)
        for line in Path(args.raw).read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]
    rows.sort(key=lambda row: row["id"])

    if not rows:
        raise SystemExit("no rows")

    instruments = Path(args.instruments)
    instruments.mkdir(parents=True, exist_ok=True)

    # one document per context window, written once
    by_window: dict[int, list[dict[str, str]]] = {}
    for row in rows:
        window = int(row["context_window_id"])
        if window in by_window:
            continue
        records = split_context(row["context_window_text"])
        check_context(row["context_window_text"], records)
        path = write_document(records, instruments / document_name(window))
        by_window[window] = records
        print(f"document {path.name}: {len(records)} records, {path.stat().st_size / 1e3:.0f} kB")

    lines: list[dict] = []
    for position, row in enumerate(rows, start=1):
        subset = position % SUBSET_EVERY == 0
        lines.append(
            build_instance(
                row,
                document_file=document_name(int(row["context_window_id"])),
                subset=subset,
                seed=SEED,
            )
        )

    instrument_path = instruments / "oolong-bridge-50.jsonl"
    instrument_path.write_text(
        "".join(json.dumps(line, ensure_ascii=False) + "\n" for line in lines), encoding="utf-8"
    )
    subset_count = sum(1 for line in lines if line["meta"]["subset"])
    print(f"instrument: {len(lines)} instances, {subset_count} in the subset")

    def query(line: dict) -> dict:
        document = Path(args.instruments) / line["evidence"]["file"]
        return {
            "id": line["instance_id"],
            "expect": "answerable",
            "text": line["query"],
            "env": {"LENS_DOCUMENTS": str(document)},
        }

    main_campaign = {
        "name": "m11-w3",
        "repeats": 1,
        "note": (
            "I1, the OOLONG bridge: document mode, one fixed document per instance, flat prompt "
            "(A0-doc) against the loop (A2-doc). Mechanism test only - it may not support a claim "
            "about retrieval, citations, the gate or the corpus. The 50 trec_coarse instances at "
            "131072 come from the release's **validation** split, which is the only split that "
            "carries trec_coarse at all; each query carries its own LENS_DOCUMENTS. Generated by "
            "scripts/build_oolong_bridge.py - do not edit by hand."
        ),
        "arms": ARMS,
        "queries": [query(line) for line in lines if not line["meta"]["subset"]],
    }
    subset_campaign = {
        "name": "m11-w3-subset",
        "repeats": 3,
        "note": (
            "I1 repeat subset at n=3: every fifth instance in sorted id order, 10 of 50, both "
            "arms. Its purpose is the run-to-run spread of exact match on a task with a short "
            "answer, which the single-run bridge cannot estimate."
        ),
        "arms": ARMS,
        "queries": [query(line) for line in lines if line["meta"]["subset"]],
    }

    campaigns = Path(args.campaigns)
    for payload, expected in ((main_campaign, 80), (subset_campaign, 60)):
        path = campaigns / f"{payload['name']}.json"
        path.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        runs = len(payload["queries"]) * len(payload["arms"]) * int(payload.get("repeats") or 1)
        status = "ok" if runs == expected else f"EXPECTED {expected}"
        print(f"{path.name}: {len(payload['queries'])} queries x 2 arms = {runs} runs  {status}")

    print(f"repo root {config.REPO_ROOT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
